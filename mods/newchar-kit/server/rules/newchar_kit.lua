  if not isAux then
    local js = pick_job_set(JOB_SETS[prof], adv)
    if js then mail_all("Starter Kit - JobSet", "BUFF swap set (12)", js) end
  end

  -- 毕业武器
  if JOB_WEAPONS[prof] then
    mail_all("Starter Kit - Weapon", "Graduation weapons", JOB_WEAPONS[prof])
