-- 把一串模板按每封 <= 11 件切分发邮件
local function mail_all(prefix, note, tpls)
  local per = 11
  local i, part = 1, 1
  while i <= #tpls do
    local att = {}
    for _ = 1, per do
      if tpls[i] then att[#att + 1] = { id = tpls[i], count = 1 }; i = i + 1 end
    end
    local total = math.ceil(#tpls / per)
    send_mail(string.format("%s %d/%d", prefix, part, total), note, att)
    part = part + 1
  end
end

-- 职业套装：先找同档；没有就找「向上最近」的一档；再没有就取最高档
-- （与 Python 工具 pick_job_set 的口径一致）
local function pick_job_set(rows, adv)
  if not rows then return nil end
  local above, aboveTier = nil, nil      -- 向上最近的
  local top, topTier = nil, nil          -- 最高档
  for _, r in ipairs(rows) do
    for _, t in ipairs(r[1]) do
      if t == adv then return r[2] end
      if t > adv and (aboveTier == nil or t < aboveTier) then
        above, aboveTier = r[2], t
      end
      if topTier == nil or t > topTier then
        top, topTier = r[2], t
      end
    end
  end
  return above or top
end

